export async function seedAttributes(prisma: PrismaClient) {

  for (const attribute of attributes) {

    const group = await prisma.attributeGroup.findUnique({
      where: {
        slug: attribute.groupSlug,
      },
    });

    if (!group) {
      console.log(`Group not found: ${attribute.groupSlug}`);
      continue;
    }
    

    await prisma.attribute.upsert({
      where: {
        slug: attribute.slug,
      },
      update: {
        name: attribute.name,
        slug: attribute.slug,
        section: attribute.section,
        description: attribute.description,
        valueType: attribute.valueType as any,
        numberType: attribute.numberType as NumberType,
        allowMultiple: attribute.allowMultiple,
        maxSelections: attribute.maxSelections ?? null,
        groupId: group.id,
        filterType: (attribute.filterType ?? "text") as FilterType,
        unit: attribute.unit as UnitType,
      },
      create: {
        name: attribute.name,
        slug: attribute.slug,
        section: attribute.section,
        description: attribute.description,
        valueType: attribute.valueType as any,
        numberType: attribute.numberType as NumberType,
        allowMultiple: attribute.allowMultiple,
        maxSelections: attribute.maxSelections ?? null,
        groupId: group.id,
        filterType: (attribute.filterType ?? "text") as FilterType,
        unit: attribute.unit as UnitType,
      },
    });

  }
}
